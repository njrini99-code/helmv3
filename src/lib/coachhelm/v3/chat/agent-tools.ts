type Sb = SupabaseClient<Database>;

/** Tool names whose execution must be gated behind an explicit coach approval. */
const CONFIRM_REQUIRED_TOOLS = [
  'create_recurring_practice',
  'create_focus_area',
  'create_task',
  'create_team_announcement',
] as const;

export type ConfirmRequiredTool = (typeof CONFIRM_REQUIRED_TOOLS)[number];

export function isConfirmRequired(name: string): name is ConfirmRequiredTool {
  return (CONFIRM_REQUIRED_TOOLS as readonly string[]).includes(name);
}

/**
 * Typed data parts this agent streams alongside the text.
 *
 * These are what make the answer more than prose: the renderers read them, and
 * they are persisted so a reload reproduces the same charts and cards.
 */
export interface CoachChatDataParts extends Record<string, unknown> {
  /** Human progress state, e.g. 'Reading 28 recorded rounds'. Never a tool name. */
  'progress': { label: string; tool: string };
  /** Everything a coach must see before approving a mutation. */
  'action-proposal': ActionProposal & { tool: string };
  /** Durable record of a completed mutation. */
  'action-receipt': ActionReceipt;
  /** A tool's provenance envelope, for the chart/table renderers. */
  'evidence': { tool: string; envelope: ToolEnvelope };
  /**
   * Written by the streaming route (not a tool) once the finished turn fails
   * the numeric-claim audit — see `chat/stream/route.ts`'s grounding check.
   * Carries the SAME text appended to `content` on persistence, so the note
   * appears in this live connection instead of only on the next reload.
   */
  'grounding-flag': { note: string };
  /** A validated, hashed scene the Ask thread draws (visuals/schema.ts). Written by show_visual, kept in the message. */
  'visual-artifact': ValidatedVisualArtifact;
}

