async page => {
  const context = await page.context().browser().newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  const p=await context.newPage();
  const report={errors:[],checks:{}};
  p.on('pageerror',e=>report.errors.push(e.message));
  await p.route('**/*',r=>r.request().url().startsWith('http://127.0.0.1:8768/')?r.continue():r.abort());
  const url='http://127.0.0.1:8768/golf/dashboard/rounds/continue/fixture?case=around';
  const saved=async()=>JSON.parse(await p.locator('[data-fixture-ledger]').getAttribute('data-fixture-ledger'));
  await p.goto(url);
  await p.getByRole('button',{name:'View shot 2',exact:true}).click();
  await p.getByRole('spinbutton',{name:'Distance to hole after shot'}).fill('19');
  await p.getByRole('button',{name:'Save Changes',exact:true}).click();
  await p.getByRole('dialog').waitFor({state:'hidden'});
  await p.waitForFunction(()=>document.querySelector('section[aria-label="Current shot context"]').textContent.includes('19 yds'));
  let ledger=await saved();
  if(ledger.length!==2||ledger[1].after.originalValue!==19||ledger[1].miss!=='short_right'||ledger[1].after.originalUnit!=='yards') throw new Error('Edit lost original fields');
  report.checks.edit=true;
  await p.getByRole('button',{name:'Undo last shot',exact:true}).click();
  await p.getByRole('button',{name:'Confirm',exact:true}).click();
  await p.getByRole('heading',{name:'Shot 2 · Approach'}).waitFor();
  ledger=await saved();
  if(ledger.length!==1||ledger[0].after.originalValue!==158) throw new Error('Undo did not preserve surviving ledger');
  report.checks.undo=true;
  await p.goto(url);
  await p.getByRole('button',{name:'Add penalty stroke',exact:true}).click();
  await p.getByRole('button',{name:'Out of Bounds',exact:true}).click();
  await p.getByRole('button',{name:'Add +1 Stroke',exact:true}).click();
  await p.getByRole('dialog').waitFor({state:'hidden'});
  await p.getByRole('heading',{name:'Shot 4 · Approach'}).waitFor();
  ledger=await saved();
  if(ledger.length!==3||ledger[2].penalty?.type!=='ob'||ledger[2].after.originalValue!==158) throw new Error('Penalty replay origin changed');
  if(await p.locator('[data-slot=course-drawing] [data-shot-segment]').count()) throw new Error('Penalty drawn as flight');
  report.checks.penaltyOrigin=true;
  await p.screenshot({path:'output/playwright/course-geometry/entry-ob-replay-390.png'});
  await p.goto(url);
  await p.evaluate(()=>localStorage.setItem('golf_distance_unit_pref','meters'));
  await p.reload();
  await p.waitForFunction(()=>document.querySelector('section[aria-label="Current shot context"]').textContent.includes('16 m'));
  if((await saved())[1].after.originalValue!==17) throw new Error('Display preference changed recorded distance');
  report.checks.metersDisplay=true;
  await p.evaluate(()=>localStorage.removeItem('golf_distance_unit_pref'));
  await p.goto(url);
  await p.evaluate(()=>document.documentElement.style.fontSize='32px');
  await p.getByRole('button',{name:'Expand course view'}).click();
  await p.getByRole('dialog').waitFor();
  await p.screenshot({path:'output/playwright/course-geometry/entry-expanded-large-text-390.png'});
  await p.keyboard.press('Escape');
  if(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw new Error('Large text overflow');
  report.checks.largeText=true;
  await p.goto('http://127.0.0.1:8768/golf/dashboard/rounds/fixture/review?hole=7&case=rolloff');
  await p.getByRole('button',{name:'Shot 4',exact:true}).click();
  await p.getByRole('button',{name:'Putting',exact:true}).click();
  await p.getByText('21 ft remaining', {exact:false}).waitFor();
  report.checks.rolloffUnits=true;
  await p.setViewportSize({width:1280,height:900});
  await p.goto('http://127.0.0.1:8768/golf/dashboard/rounds/fixture/review?hole=7');
  await p.getByRole('button',{name:'Shot 2',exact:true}).click();
  await p.locator('[data-scene-context=review]').evaluate(el=>scrollTo(0,scrollY+el.getBoundingClientRect().top-80));
  await p.screenshot({path:'output/playwright/course-geometry/review-desktop-1280.png'});
  const a=await p.locator('[data-scene-context=review]').boundingBox();
  const b=await p.getByRole('group',{name:'Recorded shots',exact:true}).boundingBox();
  if(b.x<a.x+a.width) throw new Error('Desktop details not beside geometry');
  report.checks.desktopSideBySide=true;
  await context.close();
  if(report.errors.length) throw new Error(JSON.stringify(report.errors));
  await page.evaluate(report=>window.__golfInteractionReport=report,report);
}
