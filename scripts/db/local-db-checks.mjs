#!/usr/bin/env node
/**
 * local-db-checks.mjs — pre-push ratchet for `supabase db advisors` and
 * `supabase db lint` against the LOCAL database.
 *
 * WHY THIS EXISTS
 *
 * `db:advisor-ratchet` watches production's advisor counts weekly, after a
 * migration has shipped. This runs the same advisor lints (plus the plpgsql
 * function linter) against a local stack built from the migrations, so a new
 * finding shows up before the PR does. Both commands already fail on findings
 * that exist today (security-definer views, a function that needs an
 * extension missing locally), so a plain `--fail-on` would always be red.
 * Instead every finding is keyed by rule + object and compared against
 * `supabase/local-db-checks-baseline.json`: only a key that is not in the
 * baseline fails.
 *
 * LOCAL-ONLY. Talks to SUPABASE_LOCAL_DB_URL (default: the local stack's
 * well-known postgres:postgres@127.0.0.1:54322). It refuses any other host.
 *
 * Usage:
 *   npm run db:check:local              # stack must be running (Docker or native)
 *   npm run db:check:local -- --update  # re-baseline after fixing or accepting findings
 *
 * Exit 0: no new findings.  Exit 1: new findings.  Exit 2: could not run.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const BASELINE_PATH = resolve(ROOT, 'supabase/local-db-checks-baseline.json');
const CLI = process.env.SUPABASE_CLI ?? resolve(ROOT, 'node_modules/.bin/supabase');
const DB_URL =
  process.env.SUPABASE_LOCAL_DB_URL ?? 'postgresql://postgres:postgres@127.0.0.1:54322/postgres';

/** Advisor findings carry a stable cache_key; fall back to name + detail. */
export function advisorKeys(findings) {
  return (Array.isArray(findings) ? findings : []).map(
    (f) => `advisor:${f.cache_key ?? `${f.name}:${f.detail ?? ''}`}`,
  );
}

/** `db lint` reports { results: [{ function, issues: [{ level, message }] }] }. */
export function lintKeys(report) {
  const keys = [];
  for (const r of report?.results ?? []) {
    for (const issue of r.issues ?? []) {
      keys.push(`lint:${r.function}:${issue.level}:${issue.message}`);
    }
  }
  return keys;
}

/** Keys present now but absent from the baseline, sorted and de-duplicated. */
export function newFindings(current, baseline) {
  const known = new Set(baseline);
  return [...new Set(current)].filter((k) => !known.has(k)).sort();
}

export function isLocalUrl(url) {
  try {
    return ['127.0.0.1', 'localhost', '::1', '[::1]'].includes(new URL(url).hostname);
  } catch {
    return false;
  }
}

/** The CLI prints progress lines before the JSON document; take the JSON. */
function parseJsonTail(text, opener) {
  const i = text.indexOf(opener);
  if (i < 0) throw new Error('no JSON in CLI output');
  return JSON.parse(text.slice(i, text.lastIndexOf(opener === '[' ? ']' : '}') + 1));
}

function runCli(args) {
  const res = spawnSync(CLI, [...args, '--db-url', DB_URL], { encoding: 'utf8' });
  if (res.error) throw res.error;
  return `${res.stdout ?? ''}`;
}

function main() {
  if (!isLocalUrl(DB_URL)) {
    console.error(`local-db-checks: refusing non-local database URL host (${new URL(DB_URL).hostname}).`);
    return 2;
  }
  let keys;
  try {
    const advisors = parseJsonTail(
      runCli(['db', 'advisors', '--type', 'all', '--level', 'warn', '--fail-on', 'none', '-o', 'json']),
      '[',
    );
    const lint = parseJsonTail(runCli(['db', 'lint', '--level', 'error', '--fail-on', 'none']), '{');
    keys = [...advisorKeys(advisors), ...lintKeys(lint)];
  } catch (err) {
    console.error(`local-db-checks: could not run against the local stack: ${err.message}`);
    console.error('Start one first (see the helm-supabase skill, "Testing paths").');
    return 2;
  }

  if (process.argv.includes('--update')) {
    const sorted = [...new Set(keys)].sort();
    writeFileSync(
      BASELINE_PATH,
      `${JSON.stringify({ $note: 'Generated by npm run db:check:local -- --update. Fix findings to shrink it; never add a key to pass.', keys: sorted }, null, 2)}\n`,
    );
    console.log(`local-db-checks: baseline written (${sorted.length} keys).`);
    return 0;
  }
  if (!existsSync(BASELINE_PATH)) {
    console.error('local-db-checks: no baseline. Run with --update to create one.');
    return 2;
  }
  const baseline = JSON.parse(readFileSync(BASELINE_PATH, 'utf8')).keys ?? [];
  const added = newFindings(keys, baseline);
  if (added.length === 0) {
    console.log(`local-db-checks: OK (${new Set(keys).size} findings, none new).`);
    return 0;
  }
  console.error(`local-db-checks: ${added.length} new finding(s):`);
  for (const k of added) console.error(`  ${k}`);
  return 1;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  process.exit(main());
}
