#!/usr/bin/env node
/**
 * gen-entry-points.mjs — regenerate the entry-point table in AGENTS.md.
 *
 * "What can I invoke, and when?" is answered today only by reading
 * `.claude/commands/`, `.claude/agents/`, and `.claude/skills/` directory
 * listings by hand. This generates one table from those directories' own
 * frontmatter `description:` fields (the single source each already
 * maintains for its own purpose — command-palette text, agent dispatch,
 * skill discovery) into an `AUTOGEN:entry-points` block in AGENTS.md, the
 * same mechanism scripts/regen-docs.mjs uses for memory/glossary.md.
 *
 * Scope is deliberately repo-local only: `.claude/commands|skills|agents`
 * in *this* repo, never the account-wide plugin skills a session may also
 * have loaded — those aren't checked into this repo, aren't stable across
 * sessions, and would blow the front-door token budget (see
 * check-front-door.mjs) by an order of magnitude.
 *
 * Lives in docs/generated/, not inline in AGENTS.md: `docs:rules-current`
 * caps AGENTS.md + CLAUDE.md + the always-on rules at 300 lines combined,
 * and that cap had zero headroom before this generator existed. AGENTS.md
 * instead carries a three-line pointer to this file.
 *
 * Usage:
 *   node scripts/knowledge/gen-entry-points.mjs            # write
 *   node scripts/knowledge/gen-entry-points.mjs --check    # verify, no write
 *
 * Deps: js-yaml (repo dependency, used by every other knowledge/*.mjs
 * checker to parse YAML/frontmatter).
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import * as yaml from 'js-yaml';

const ROOT = process.cwd();
const OUTPUT = join(ROOT, 'docs', 'generated', 'ENTRY_POINTS.md');
const MAX_DESC_LEN = 200;

function readFrontmatter(filePath) {
  const raw = readFileSync(filePath, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return {};
  try {
    return yaml.load(m[1]) || {};
  } catch {
    return {};
  }
}

function truncate(s, max) {
  if (!s) return '';
  const clean = s.replace(/\s+/g, ' ').trim();
  if (clean.length <= max) return clean;
  const cut = clean.slice(0, max);
  const lastSpace = cut.lastIndexOf(' ');
  return `${cut.slice(0, lastSpace > 40 ? lastSpace : max)}…`;
}

function collectCommands() {
  const dir = join(ROOT, '.claude', 'commands');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .map((f) => {
      const fm = readFrontmatter(join(dir, f));
      return {
        type: 'Command',
        name: `/${f.replace(/\.md$/, '')}`,
        description: fm.description || '',
      };
    });
}

function collectAgents() {
  const dir = join(ROOT, '.claude', 'agents');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .map((f) => {
      const fm = readFrontmatter(join(dir, f));
      return {
        type: 'Agent',
        name: fm.name || f.replace(/\.md$/, ''),
        description: fm.description || '',
      };
    });
}

function collectSkills() {
  const dir = join(ROOT, '.claude', 'skills');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => statSync(join(dir, f)).isDirectory())
    .map((d) => {
      const skillPath = join(dir, d, 'SKILL.md');
      if (!existsSync(skillPath)) return null;
      const fm = readFrontmatter(skillPath);
      return {
        type: 'Skill',
        name: fm.name || d,
        description: fm.description || '',
      };
    })
    .filter(Boolean);
}

function renderTable(entries) {
  const sorted = [...entries].sort((a, b) => {
    if (a.type !== b.type) return a.type.localeCompare(b.type);
    return a.name.localeCompare(b.name);
  });
  const lines = [
    '| Name | Type | When to use |',
    '| --- | --- | --- |',
  ];
  for (const e of sorted) {
    lines.push(`| \`${e.name}\` | ${e.type} | ${truncate(e.description, MAX_DESC_LEN)} |`);
  }
  return lines.join('\n');
}

function renderDoc(entries, table) {
  return [
    '# Entry Points',
    '',
    '<!-- GENERATED by scripts/knowledge/gen-entry-points.mjs — do not edit. -->',
    '<!-- Regenerate: npm run knowledge:entry-points  ·  Verify: npm run knowledge:entry-points:check -->',
    '',
    'Repo-local commands, agents, and skills — one line each, from each entry\'s ' +
      'own frontmatter `description:`. Not the account-wide plugin skills a session ' +
      'may also have loaded (see `AGENTS.md`\'s Entry points section for why those ' +
      'are out of scope here).',
    '',
    table,
    '',
  ].join('\n');
}

function main() {
  const entries = [...collectCommands(), ...collectAgents(), ...collectSkills()];
  const table = renderTable(entries);
  const updated = renderDoc(entries, table);
  let current = null;
  try { current = readFileSync(OUTPUT, 'utf8'); } catch (err) { if (!err || err.code !== 'ENOENT') throw err; }

  if (process.argv.includes('--check')) {
    if (updated !== current) {
      console.error(
        '❌ docs/generated/ENTRY_POINTS.md is stale. Run `npm run knowledge:entry-points` and commit the result.',
      );
      process.exit(1);
    }
    console.log(`✅ docs/generated/ENTRY_POINTS.md is current (${entries.length} entries).`);
    process.exit(0);
  }

  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, updated);
  console.log(`Wrote ${entries.length} entry-point rows to docs/generated/ENTRY_POINTS.md.`);
}

main();
