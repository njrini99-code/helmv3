#!/usr/bin/env node
/**
 * Generates `src/lib/admin/slo/golden-paths.generated.ts` from
 * `memory/journeys/golden-paths.yml`, per Bridge Control Plane Phase D.6.
 *
 * WHY THIS EXISTS: golden-path health (`src/lib/admin/slo/golden-path-health.ts`)
 * reads the journey/stage list at REQUEST time, inside a server component.
 * `memory/**` is not part of the Vercel function bundle (same reason
 * `src/lib/flags/registry.generated.ts` exists for `config/feature-flags.yml`
 * — see that generator's own header) — an `fs.readFile` of the YAML would
 * work locally and fail in production. This compiles the (small) subset of
 * fields the health module actually needs into a typed constant.
 *
 * Deliberately narrow: only `id`/`name`/`role`/`criticality`/`status` per
 * journey and `id`/`feature_id` per stage. Everything else in the YAML
 * (observable_signals citations, environment_strategy, notes) is
 * documentation for `check-journeys.mjs` and human readers, not a runtime
 * health input — keeping it out of the generated file means a citation edit
 * never requires regenerating this module.
 *
 * Refuses to write (or, in `--check` mode, reports drift) when the source
 * YAML fails `check-journeys.mjs`'s own structural validation — the
 * generator does not re-decide what "valid" means, it reuses the one
 * checker so the two can never disagree.
 *
 * `--check`: non-mutating, byte-for-byte comparison against what's on disk.
 * Same pattern as `flags:generate --check` / `docs:inventory-check`.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import * as yaml from 'js-yaml';
import { loadRegistry } from './lib/registry.mjs';
import { validateJourneysDoc } from './check-journeys.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const YAML_PATH = resolve(ROOT, 'memory/journeys/golden-paths.yml');
const OUT_PATH = resolve(ROOT, 'src/lib/admin/slo/golden-paths.generated.ts');

function renderModule(doc) {
  const journeys = doc.journeys.map((j) => ({
    id: j.id,
    name: j.name,
    role: j.role,
    criticality: j.criticality,
    status: j.status,
    stages: j.stages.map((s) => ({ id: s.id, featureId: s.feature_id })),
  }));

  const body = journeys
    .map(
      (j) => `  {
    id: ${JSON.stringify(j.id)},
    name: ${JSON.stringify(j.name)},
    role: ${JSON.stringify(j.role)},
    criticality: ${JSON.stringify(j.criticality)},
    status: ${JSON.stringify(j.status)},
    stages: [
${j.stages.map((s) => `      { id: ${JSON.stringify(s.id)}, featureId: ${JSON.stringify(s.featureId)} },`).join('\n')}
    ],
  },`,
    )
    .join('\n');

  return `// AUTOGENERATED — DO NOT EDIT BY HAND.
//
// Generated by \`npm run knowledge:golden-paths-generate\`
// (scripts/knowledge/gen-golden-paths.mjs) from
// memory/journeys/golden-paths.yml. A stamp saying so is not evidence this
// file is current — \`npm run knowledge:golden-paths-generate:check\`
// re-derives it independently and fails on drift.
//
// Compiled to a typed constant so golden-path health never reads
// memory/** at request time — that directory is not in the Vercel function
// bundle. See this generator's own header for why, and for exactly which
// fields were kept (id/name/role/criticality/status, and per stage
// id/feature_id only).

export interface GeneratedGoldenPathStage {
  readonly id: string;
  readonly featureId: string;
}

export interface GeneratedGoldenPath {
  readonly id: string;
  readonly name: string;
  readonly role: 'player' | 'coach';
  readonly criticality: 'high' | 'medium' | 'low';
  readonly status: 'active' | 'collecting';
  readonly stages: readonly GeneratedGoldenPathStage[];
}

export const GOLDEN_PATHS: readonly GeneratedGoldenPath[] = [
${body}
] as const;
`;
}

async function main() {
  const checkMode = process.argv.includes('--check');

  if (!existsSync(YAML_PATH)) {
    console.error(`gen-golden-paths: ${YAML_PATH} does not exist.`);
    process.exit(1);
  }

  const doc = yaml.load(readFileSync(YAML_PATH, 'utf8'));

  const registry = await loadRegistry(ROOT);
  const registryFeatureIds = new Set(Object.keys(registry.features ?? {}));
  let tracked;
  try {
    tracked = new Set(execFileSync('git', ['ls-files'], { cwd: ROOT, encoding: 'utf8' }).trim().split('\n').filter(Boolean));
  } catch {
    tracked = new Set();
  }
  const fileTracked = (p) => typeof p === 'string' && tracked.has(p);
  const readFileText = (p) => readFileSync(resolve(ROOT, p), 'utf8');

  const problems = validateJourneysDoc(doc, { registryFeatureIds, readFileText, fileTracked });
  if (problems.length > 0) {
    console.error(`gen-golden-paths: refused — ${problems.length} problem(s) in memory/journeys/golden-paths.yml (run \`npm run knowledge:journeys-check\` for detail):`);
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }

  const rendered = renderModule(doc);

  if (checkMode) {
    if (!existsSync(OUT_PATH)) {
      console.error(`gen-golden-paths --check: ${OUT_PATH} does not exist. Run \`npm run knowledge:golden-paths-generate\`.`);
      process.exit(1);
    }
    const onDisk = readFileSync(OUT_PATH, 'utf8');
    if (onDisk !== rendered) {
      console.error('gen-golden-paths --check: golden-paths.generated.ts is stale relative to memory/journeys/golden-paths.yml.');
      console.error('Run `npm run knowledge:golden-paths-generate` and commit the result.');
      process.exit(1);
    }
    console.log(`gen-golden-paths --check: golden-paths.generated.ts is current (${doc.journeys.length} journeys).`);
    return;
  }

  writeFileSync(OUT_PATH, rendered, 'utf8');
  console.log(`Wrote ${OUT_PATH} (${doc.journeys.length} journeys).`);
}

main();
