#!/usr/bin/env node
/**
 * The Bridge numbers itself (plan §6, owner decision D4). Every control and state on a Bridge screen carries a
 * `BR-<screen><nn>` code as `data-br`; config/bridge/contracts.json lists each with its screen, label and what it
 * does, and this script writes the readable map from it: docs/bridge/generated/BRIDGE_UI_MAP.md.
 *
 * Deterministic: sorted by code, no dates, no commit ids. `clubhouse:check` runs the check (scripts/clubhouse/check.mjs),
 * and src/app/admin/clubhouse/__tests__/bridge-contracts.test.ts holds contracts.json to br-codes.ts and to every
 * data-br under src/app/admin.
 *
 *   node scripts/clubhouse/bridge-ui-map.mjs           write the map
 *   node scripts/clubhouse/bridge-ui-map.mjs --check   exit 1 if the map is stale or the contracts are malformed
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const CONTRACTS_PATH = 'config/bridge/contracts.json';
export const UI_MAP_PATH = 'docs/bridge/generated/BRIDGE_UI_MAP.md';

const cell = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** The contract file's own rules: one row per code, each on a screen that exists and whose number it carries. */
export function checkBridgeContracts(contracts) {
  const v = [];
  const at = CONTRACTS_PATH;
  const screens = contracts?.screens ?? {};
  const seen = new Set();
  for (const [id, s] of Object.entries(screens)) {
    if (!/^B\d{2}$/.test(id)) v.push(`${at}: screen "${id}" is not B##`);
    if (!s?.name) v.push(`${at}: screen ${id} has no name`);
  }
  for (const row of contracts?.codes ?? []) {
    const code = row?.code;
    if (!/^BR-\d{4}$/.test(code ?? '')) {
      v.push(`${at}: "${code}" is not BR-####`);
      continue;
    }
    if (seen.has(code)) v.push(`${at}: ${code} is listed twice`);
    seen.add(code);
    if (!screens[row.screen]) v.push(`${at}: ${code} is on ${row.screen}, which is not in screens`);
    else if (`B${code.slice(3, 5)}` !== row.screen) v.push(`${at}: ${code} belongs to B${code.slice(3, 5)}, not ${row.screen}`);
    if (!row.label?.trim()) v.push(`${at}: ${code} has no label`);
    if (!row.does?.trim()) v.push(`${at}: ${code} does not say what it does`);
    if (!/^[a-z]+\.[A-Za-z]+$/.test(row.key ?? '')) v.push(`${at}: ${code} key "${row.key}" is not <screen>.<control> as in br-codes.ts`);
  }
  const sorted = [...(contracts?.codes ?? [])].map((r) => r.code);
  if (sorted.join() !== [...sorted].sort().join()) v.push(`${at}: codes are not sorted by code`);
  return v;
}

export function renderBridgeUiMap(contracts) {
  const screens = contracts.screens ?? {};
  const codes = contracts.codes ?? [];
  let md = '# Bridge UI map\n\n';
  md += `<!-- Generated by node scripts/clubhouse/bridge-ui-map.mjs from ${CONTRACTS_PATH}. Do not edit. -->\n\n`;
  md += 'Every control and state on the Bridge\'s own screens, by its `BR-` code (plan §6, owner decision D4). ';
  md += 'Each code sits on its element as `data-br`. The four states repeat on every screen: xx90 loading, xx91 empty, ';
  md += 'xx92 failed to load, xx93 no signal yet.\n\n';
  md += '| Screen | Name | Route | Codes |\n| --- | --- | --- | --- |\n';
  for (const [id, s] of Object.entries(screens).sort(([a], [b]) => a.localeCompare(b))) {
    md += `| ${id} | ${cell(s.name)} | ${cell(s.route)} | ${codes.filter((c) => c.screen === id).length} |\n`;
  }
  md += `\n${codes.length} codes in all.\n`;
  for (const [id, s] of Object.entries(screens).sort(([a], [b]) => a.localeCompare(b))) {
    const mine = codes.filter((c) => c.screen === id);
    if (!mine.length) continue;
    md += `\n## ${id} ${s.name}\n\n| Code | Label | Does | In code |\n| --- | --- | --- | --- |\n`;
    for (const c of mine) md += `| ${c.code} | ${cell(c.label)} | ${cell(c.does)} | \`BR.${c.key}\` |\n`;
  }
  return md;
}

/** For check.mjs: the contract rules plus "is the generated map current". */
export function runBridgeUiMapCheck(root) {
  const p = join(root, CONTRACTS_PATH);
  if (!existsSync(p)) return [`${CONTRACTS_PATH} is missing`];
  let contracts;
  try {
    contracts = JSON.parse(readFileSync(p, 'utf8'));
  } catch (err) {
    return [`${CONTRACTS_PATH} is not JSON: ${err.message}`];
  }
  const v = checkBridgeContracts(contracts);
  const out = join(root, UI_MAP_PATH);
  if (!existsSync(out) || readFileSync(out, 'utf8') !== renderBridgeUiMap(contracts)) {
    v.push(`${UI_MAP_PATH} is stale; run node scripts/clubhouse/bridge-ui-map.mjs`);
  }
  return v;
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
  if (process.argv.includes('--check')) {
    const v = runBridgeUiMapCheck(root);
    if (v.length) {
      console.error(`bridge ui map: ${v.length} violation(s):`);
      for (const x of v) console.error('  ' + x);
      process.exit(1);
    }
    console.log('bridge ui map current.');
    return;
  }
  const contracts = JSON.parse(readFileSync(join(root, CONTRACTS_PATH), 'utf8'));
  const v = checkBridgeContracts(contracts);
  if (v.length) {
    for (const x of v) console.error('  ' + x);
    process.exit(1);
  }
  mkdirSync(dirname(join(root, UI_MAP_PATH)), { recursive: true });
  writeFileSync(join(root, UI_MAP_PATH), renderBridgeUiMap(contracts));
  console.log(`bridge ui map: ${contracts.codes.length} codes written to ${UI_MAP_PATH}.`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
