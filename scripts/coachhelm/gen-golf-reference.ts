/**
 * Writes `src/lib/coachhelm/v3/chat/golf-reference.generated.ts` from `docs/v3-research-golf-domain.md`.
 *
 *   npm run coachhelm:golf-reference           write the module
 *   npm run coachhelm:golf-reference -- --check  exit 1 when it is out of date
 *
 * A test (`golf-reference.test.ts`) also recomputes it, so a doc edit without a regenerate fails CI.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { splitGolfReference } from '../../src/lib/coachhelm/v3/chat/golf-reference-split';

const root = process.cwd();
const docPath = resolve(root, 'docs/v3-research-golf-domain.md');
const outPath = resolve(root, 'src/lib/coachhelm/v3/chat/golf-reference.generated.ts');

export function renderGolfReferenceModule(markdown: string): string {
  const sections = splitGolfReference(markdown);
  return `// GENERATED by scripts/coachhelm/gen-golf-reference.ts from docs/v3-research-golf-domain.md. Do not edit by hand.
// Regenerate: npm run coachhelm:golf-reference
import type { GolfReferenceSection } from './golf-reference-split';

export const GOLF_REFERENCE_SECTIONS: readonly GolfReferenceSection[] = ${JSON.stringify(sections, null, 2)};
`;
}

const next = renderGolfReferenceModule(readFileSync(docPath, 'utf8'));
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    /* missing counts as out of date */
  }
  if (current !== next) {
    console.error('golf-reference.generated.ts is out of date: run npm run coachhelm:golf-reference');
    process.exit(1);
  }
  console.log('golf-reference.generated.ts is up to date');
} else {
  writeFileSync(outPath, next);
  console.log(`wrote ${outPath}`);
}
