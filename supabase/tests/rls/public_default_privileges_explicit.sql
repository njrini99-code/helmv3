-- Data API grants are explicit in schema public
-- (migration 20261003120000_public_default_privileges_explicit.sql).
--
-- Supabase stops auto-granting new public tables to the Data API roles on
-- 2026-10-30. This suite pins the same contract locally and in CI:
--   1. No default ACL entry for grantor postgres in public hands table or
--      sequence privileges to anon, authenticated or service_role.
--   2. Every existing public table is still readable by service_role. The
--      default change must not have removed grants that server code depends on.
--   3. A table postgres creates now starts with no grants for those roles.
--      SET LOCAL ROLE postgres matters: a supabase_admin session would pick
--      up supabase_admin's own (platform-owned) defaults instead.
\ir _helpers.sql

BEGIN;
SELECT plan(4);

SELECT is_empty(
  $$
    SELECT pg_catalog.pg_get_userbyid(a.grantee) AS grantee,
           d.defaclobjtype AS objtype,
           a.privilege_type
    FROM pg_catalog.pg_default_acl d
    CROSS JOIN LATERAL pg_catalog.aclexplode(d.defaclacl) a
    WHERE d.defaclnamespace = 'public'::regnamespace
      AND pg_catalog.pg_get_userbyid(d.defaclrole) = 'postgres'
      AND d.defaclobjtype IN ('r', 'S')
      AND pg_catalog.pg_get_userbyid(a.grantee) IN ('anon', 'authenticated', 'service_role')
  $$,
  'postgres default privileges in public grant no table/sequence access to anon, authenticated or service_role'
);

SELECT is_empty(
  $$
    SELECT c.relname
    FROM pg_catalog.pg_class c
    WHERE c.relnamespace = 'public'::regnamespace
      AND c.relkind IN ('r', 'p')
      AND NOT pg_catalog.has_table_privilege('service_role', c.oid, 'SELECT')
  $$,
  'every public base table is SELECT-able by service_role'
);

-- Probe: a table created by postgres after the migration gets no Data API
-- grants. Rolled back with the rest of the suite.
SET LOCAL ROLE postgres;
CREATE TABLE public.zz_default_grants_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
RESET ROLE;

SELECT is_empty(
  $$
    SELECT grantee, privilege_type
    FROM information_schema.role_table_grants
    WHERE table_schema = 'public'
      AND table_name = 'zz_default_grants_probe'
      AND grantee IN ('anon', 'authenticated', 'service_role')
  $$,
  'a new public table created by postgres has no anon/authenticated/service_role grants'
);

SELECT is_empty(
  $$
    SELECT r.rolname
    FROM pg_catalog.pg_roles r
    WHERE r.rolname IN ('anon', 'authenticated', 'service_role')
      AND pg_catalog.has_sequence_privilege(
        r.rolname,
        pg_catalog.pg_get_serial_sequence('public.zz_default_grants_probe', 'id'),
        'USAGE'
      )
  $$,
  'the new table''s identity sequence has no anon/authenticated/service_role USAGE'
);

SELECT * FROM finish();
ROLLBACK;
