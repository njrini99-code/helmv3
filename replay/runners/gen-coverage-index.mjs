#!/usr/bin/env node
// replay/runners/gen-coverage-index.mjs
//
// Generates src/lib/admin/replay/coverage-index.generated.ts from
// replay/manifests/*.yml + replay/proofs/*.json.
//
// WHY GENERATED RATHER THAN READ AT RUNTIME: this codebase has no precedent
// for a server component reading an arbitrary repo-root file via fs at
// request time — checked directly (src/lib/admin/triage/feature-
// constellation.ts's own header records the same check coming up empty for
// docs/generated/WORLD_MODEL.json) — and Vercel's serverless output file
// tracing is not guaranteed to include files outside src/ that no module
// imports. A bundled, statically-imported TS array sidesteps that risk
// entirely. Re-run this after adding/editing a manifest or a proof:
//
//   node replay/runners/gen-coverage-index.mjs
//
// There is no CI drift check wired for this generator yet (unlike
// scripts/regen-docs.mjs's AUTOGEN blocks) — see replay/README.md and the
// PR that introduced this file for that known gap.

import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { REPLAY_DIR, PROOFS_DIR, listManifestFiles, loadManifest } from './manifest.mjs';

const OUT_PATH = join(REPLAY_DIR, '..', 'src', 'lib', 'admin', 'replay', 'coverage-index.generated.ts');

function loadProof(replayId) {
  const p = join(PROOFS_DIR, `${replayId}.json`);
  if (!existsSync(p)) return null;
  return JSON.parse(readFileSync(p, 'utf8'));
}

function buildRows() {
  return listManifestFiles()
    .map((f) => loadManifest(f).manifest)
    .map((m) => {
      const proof = loadProof(m.replay_id);
      return {
        replayId: m.replay_id,
        incidentId: m.incident_id,
        featureId: m.feature_id,
        title: m.title,
        badVersion: m.bad_version,
        fixedVersion: m.fixed_version,
        verdict: proof?.verdict ?? 'not-yet-run',
        ranAt: proof?.ran_at ?? null,
      };
    })
    .sort((a, b) => a.replayId.localeCompare(b.replayId));
}

function render(rows) {
  const body = rows
    .map(
      (r) => `  {
    replayId: ${JSON.stringify(r.replayId)},
    incidentId: ${JSON.stringify(r.incidentId)},
    featureId: ${JSON.stringify(r.featureId)},
    title: ${JSON.stringify(r.title)},
    badVersion: ${JSON.stringify(r.badVersion)},
    fixedVersion: ${JSON.stringify(r.fixedVersion)},
    verdict: ${JSON.stringify(r.verdict)},
    ranAt: ${r.ranAt ? JSON.stringify(r.ranAt) : 'null'},
  },`,
    )
    .join('\n');

  return `// DO NOT EDIT — generated by \`node replay/runners/gen-coverage-index.mjs\`
// from replay/manifests/*.yml + replay/proofs/*.json. See replay/README.md.

export type ReplayVerdict = 'reproduced' | 'inconclusive' | 'not-yet-run';

export interface ReplayCoverageIndexRow {
  replayId: string;
  incidentId: string;
  featureId: string;
  title: string;
  badVersion: string;
  fixedVersion: string;
  verdict: ReplayVerdict;
  ranAt: string | null;
}

export const REPLAY_COVERAGE_INDEX: readonly ReplayCoverageIndexRow[] = [
${body}
];
`;
}

function main() {
  const rows = buildRows();
  writeFileSync(OUT_PATH, render(rows));
  console.log(`wrote ${rows.length} row(s) to ${OUT_PATH}`);
}

main();
