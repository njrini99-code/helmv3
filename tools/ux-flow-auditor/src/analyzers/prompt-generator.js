/**
 * ClaudePromptGenerator - Generates detailed, actionable prompts for Claude Code
 * 
 * Features:
 * - Project-specific context (YOUR patterns, YOUR conventions)
 * - Past fix history (what worked, what didn't)
 * - Deep WHY explanations
 * - Actionable HOW-to-fix instructions
 */

import { promises as fs } from 'fs';
import path from 'path';

export class ClaudePromptGenerator {
  constructor(projectRoot, codebaseGraph, memory) {
    this.projectRoot = projectRoot;
    this.codebaseGraph = codebaseGraph;
    this.memory = memory;
    
    // Issue templates with WHY and HOW
    this.issueTemplates = this.loadIssueTemplates();
  }

  /**
   * Generate a comprehensive prompt
   */
  async generate(request) {
    const { suggestion, routePath, context, similarFixes } = request;
    
    // Get route file content
    const fileContent = await this.getFileContent(routePath);
    
    // Get related files
    const relatedFiles = await this.getRelatedFiles(routePath);
    
    // Get project patterns
    const patterns = this.getProjectPatterns();
    
    // Build the prompt
    const prompt = this.buildPrompt({
      suggestion,
      routePath,
      context,
      fileContent,
      relatedFiles,
      patterns,
      similarFixes,
    });
    
    return prompt;
  }

  /**
   * Build the complete prompt
   */
  buildPrompt({ suggestion, routePath, context, fileContent, relatedFiles, patterns, similarFixes }) {
    const isFeature = suggestion.type === 'feature';
    const template = this.issueTemplates[suggestion.category] || this.issueTemplates.default;
    
    return `# ${isFeature ? '🚀 Feature Implementation' : '🔧 Issue Fix'}: ${suggestion.title}

## 📍 Location
- **Route**: \`${routePath}\`
- **File**: \`${context?.filePath || this.routeToFilePath(routePath)}\`
- **Category**: ${suggestion.category}
- **Severity**: ${suggestion.severity}
${context?.location ? `- **Specific Location**: ${context.location}` : ''}

---

## ❓ What's Wrong

${suggestion.description}

${template?.whyItMatters ? `
## 💡 Why This Matters

${template.whyItMatters}
` : ''}

---

## ✅ Your Task

${suggestion.suggestedFix || template?.howToFix || 'Fix the issue following project patterns.'}

${template?.stepByStep ? `
### Step-by-Step

${template.stepByStep}
` : ''}

---

## 📄 Current File Content

\`\`\`tsx
${fileContent?.slice(0, 3000) || 'File content not available'}
\`\`\`

${relatedFiles.length > 0 ? `
## 📁 Related Files

${relatedFiles.map(f => `### ${f.name}
\`\`\`tsx
${f.content.slice(0, 500)}
\`\`\`
`).join('\n')}
` : ''}

---

## 🎨 Project Patterns to Follow

${patterns.map(p => `- ${p}`).join('\n')}

${similarFixes?.successfulFixes?.length > 0 ? `
## 📚 What Worked Before

${similarFixes.successfulFixes.slice(0, 3).map(f => 
  `- **${f.type}**: ${f.approach} (completed in ${Math.round(f.duration/1000)}s)`
).join('\n')}
` : ''}

${similarFixes?.failedFixes?.length > 0 ? `
## ⚠️ Approaches to Avoid

${similarFixes.failedFixes.slice(0, 2).map(f => 
  `- **Don't**: ${f.approach} — *${f.reason}*`
).join('\n')}
` : ''}

---

## ✔️ Verification Checklist

1. [ ] TypeScript compiles without errors
2. [ ] ESLint passes with no warnings
3. [ ] Component renders correctly at all breakpoints
4. [ ] ${suggestion.category === 'a11y' ? 'Accessibility requirements met (aria-labels, focus states)' : 'Visual appearance matches design system'}
5. [ ] No console errors in browser
6. [ ] Loading and error states handled

---

## 📋 Expected Outcome

After this fix:
- ${suggestion.title} should be resolved
- The route should score higher on ${suggestion.category} metrics
- No regressions in existing functionality

---
*Generated by HelmDev Visual Intelligence System*
*Route: ${routePath} | Category: ${suggestion.category} | Priority: ${suggestion.severity}*`;
  }

  /**
   * Load issue templates
   */
  loadIssueTemplates() {
    return {
      ui: {
        whyItMatters: `UI inconsistencies create a unprofessional impression and can confuse users. Consistent spacing, alignment, and visual hierarchy are hallmarks of premium software. Users subconsciously notice when things don't line up.`,
        howToFix: `Analyze the spacing/alignment issue and apply consistent values from the design system. Use Tailwind's spacing scale (4, 8, 16, 24px) for consistency.`,
        stepByStep: `1. Identify the inconsistent elements
2. Check the design system for correct values
3. Apply consistent Tailwind classes
4. Test at all viewport sizes
5. Compare before/after visually`,
      },
      
      ux: {
        whyItMatters: `Poor UX leads to user frustration, abandonment, and negative perception of the product. Every interaction should feel intentional and provide appropriate feedback.`,
        howToFix: `Implement the missing feedback or interaction pattern. Focus on user expectations at each step of the flow.`,
        stepByStep: `1. Map the user journey for this interaction
2. Identify missing feedback points
3. Add loading, error, and success states
4. Add appropriate animations/transitions
5. Test the complete flow end-to-end`,
      },
      
      a11y: {
        whyItMatters: `Accessibility isn't optional - it's required for inclusive design and often mandated by law. Inaccessible interfaces exclude users with disabilities and can expose the company to legal risk.`,
        howToFix: `Add the missing accessibility attributes or patterns. Follow WCAG 2.1 AA guidelines.`,
        stepByStep: `1. Run axe or similar accessibility audit
2. Fix all critical and serious issues first
3. Add proper ARIA labels and roles
4. Ensure keyboard navigation works
5. Test with a screen reader
6. Check color contrast ratios`,
      },
      
      perf: {
        whyItMatters: `Slow pages lose users. Every 100ms of added latency reduces conversions. Performance is a feature that affects every user, every time.`,
        howToFix: `Optimize the identified performance issue. Consider lazy loading, code splitting, or caching strategies.`,
        stepByStep: `1. Measure current performance (Lighthouse, Web Vitals)
2. Identify the bottleneck
3. Apply appropriate optimization
4. Verify improvement with measurements
5. Ensure no functionality regressions`,
      },
      
      code: {
        whyItMatters: `Code quality issues accumulate as technical debt, making the codebase harder to maintain and more prone to bugs. Clean code is easier to review, debug, and extend.`,
        howToFix: `Address the code quality issue following best practices and project conventions.`,
        stepByStep: `1. Understand the issue and its implications
2. Apply the fix following project patterns
3. Run linter and type checker
4. Ensure tests still pass
5. Review for unintended side effects`,
      },
      
      feature: {
        whyItMatters: `Missing features create gaps in the user experience and may cause users to seek alternative solutions. Implementing the right features differentiates the product.`,
        howToFix: `Implement the feature following existing patterns in the codebase. Consider edge cases and error handling.`,
        stepByStep: `1. Understand the feature requirements
2. Check for existing similar patterns
3. Implement with proper TypeScript types
4. Add loading and error states
5. Test all user flows
6. Document if necessary`,
      },
      
      default: {
        whyItMatters: `This issue affects the quality and reliability of the application. Addressing it improves the overall user and developer experience.`,
        howToFix: `Analyze the issue and apply an appropriate fix following project patterns and best practices.`,
      },
    };
  }

  /**
   * Get file content for a route
   */
  async getFileContent(routePath) {
    const filePath = this.routeToFilePath(routePath);
    
    try {
      const fullPath = path.join(this.projectRoot, 'src', 'app', filePath);
      return await fs.readFile(fullPath, 'utf8');
    } catch {
      try {
        // Try alternative paths
        const altPath = path.join(this.projectRoot, 'app', filePath);
        return await fs.readFile(altPath, 'utf8');
      } catch {
        return null;
      }
    }
  }

  /**
   * Convert route path to file path
   */
  routeToFilePath(routePath) {
    // Handle dynamic routes
    let filePath = routePath
      .replace(/\[([^\]]+)\]/g, '[$1]')
      .replace(/^\//, '');
    
    return filePath ? `${filePath}/page.tsx` : 'page.tsx';
  }

  /**
   * Get related files (layout, loading, error)
   */
  async getRelatedFiles(routePath) {
    const related = [];
    const baseDir = path.join(this.projectRoot, 'src', 'app', routePath.replace(/^\//, ''));
    
    const filesToCheck = ['layout.tsx', 'loading.tsx', 'error.tsx'];
    
    for (const fileName of filesToCheck) {
      try {
        const filePath = path.join(baseDir, fileName);
        const content = await fs.readFile(filePath, 'utf8');
        related.push({ name: fileName, content });
      } catch {
        // File doesn't exist, skip
      }
    }
    
    return related;
  }

  /**
   * Get project patterns
   */
  getProjectPatterns() {
    return [
      'Use Tailwind CSS for all styling',
      'Follow glassmorphism design system (bg-white/10, backdrop-blur-md, border-white/20)',
      'Use Suspense boundaries for async components',
      'Implement loading.tsx for route-level loading states',
      'Use server actions for form submissions',
      'Prefer Server Components, use "use client" only when needed',
      'Use Lucide icons (import from lucide-react)',
      'Follow the existing component patterns in src/components',
    ];
  }

  /**
   * Save prompt to file
   */
  async savePrompt(prompt, suggestion, routePath) {
    const promptDir = path.join(this.projectRoot, '.helmdev', 'prompts', 'queued');
    await fs.mkdir(promptDir, { recursive: true });
    
    const filename = `${Date.now()}-${suggestion.category}-${suggestion.id}.md`;
    const filepath = path.join(promptDir, filename);
    
    await fs.writeFile(filepath, prompt);
    
    return filepath;
  }
}

export default ClaudePromptGenerator;
