#!/usr/bin/env node
// npm run release:prepare -- [--sha <candidate>] [--out <path>] [--json] [--no-vercel]
//
// spec §21 — compares the current production SHA to a candidate SHA (default:
// main's tip) and writes docs/releases/<candidate-sha>.md: everything a
// human needs to approve or reject the release train.
//
// The report embeds a machine-readable `RELEASE_META` JSON block inside an
// HTML comment at the top of the file. scripts/release/check-release-candidate.mjs
// parses that block back out rather than re-deriving or prose-scraping the
// report — one source of truth per report, and a report that was hand-edited
// or generated by an older version of this script fails that parse loudly
// instead of being silently trusted.
//
// This script never deploys anything and never mutates the release queue or
// ledger. It only reads repo state and writes one file under docs/releases/.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import {
  resolveRepoRoot, parseArgs, warn, resolveProductionState, resolveSha,
  commitsBetween, changedFilesBetween, mapChangedFilesToFeatures,
  classifyFileRisk, maxRiskTier, loadReleaseQueue, resolveGhRepo, gh,
  getCheckRuns, evaluateRequiredChecks, parseDeploymentLedger,
} from './lib/release-common.mjs';

const GH_PR_LOOKUP_BOUND = 25; // see repo-doctor's own "log what was dropped" habit — never silently truncate

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const repoRoot = resolveRepoRoot();

  const candidateInput = args.sha ?? 'main';
  const candidateSha = resolveSha(repoRoot, candidateInput);
  if (!candidateSha) {
    process.stderr.write(`Candidate ref "${candidateInput}" did not resolve to a commit in this repo.\n`);
    process.exit(1);
    return;
  }

  const ledger = parseDeploymentLedger(repoRoot);
  const prodState = resolveProductionState({ repoRoot, ledger, useVercel: !args['no-vercel'] });

  let commits = [];
  let changedFiles = [];
  let rangeWarning = null;
  if (prodState.sha) {
    commits = commitsBetween(repoRoot, prodState.sha, candidateSha);
    changedFiles = changedFilesBetween(repoRoot, prodState.sha, candidateSha);
  } else {
    rangeWarning =
      'Production SHA is unresolved (no Vercel access and an empty/unavailable deployment ledger), so ' +
      'commits and changed files between production and this candidate cannot be enumerated. Fix deploy-identity ' +
      'resolution before trusting this report for a real release.';
    warn(rangeWarning);
  }

  const features = await mapChangedFilesToFeatures(repoRoot, changedFiles);
  const fileRisk = changedFiles.map((f) => ({ file: f, risk: classifyFileRisk(f) }));
  const overallRisk = maxRiskTier(fileRisk.map((f) => f.risk));
  const r3Files = fileRisk.filter((f) => f.risk === 'R3');
  const migrations = changedFiles.filter((f) => f.startsWith('supabase/migrations/'));

  // PRs: prefer the squash-merge subject convention "... (#123)"; for
  // commits without one, best-effort gh lookup, bounded and logged, never
  // blocking report generation.
  const prsFromSubject = [...new Set(commits.map((c) => c.prNumber).filter(Boolean))];
  const commitsWithoutPr = commits.filter((c) => !c.prNumber);
  let ghPrLookupWarning = null;
  const prsFromGh = [];
  if (commitsWithoutPr.length > 0) {
    const { repo } = resolveGhRepo(repoRoot);
    if (repo) {
      for (const c of commitsWithoutPr.slice(0, GH_PR_LOOKUP_BOUND)) {
        const r = gh(repoRoot, ['pr', 'list', '--search', c.hash, '--state', 'merged', '--json', 'number,title,url']);
        if (r.ok && r.value) {
          try {
            const found = JSON.parse(r.value);
            if (found.length > 0) prsFromGh.push({ commit: c.short, ...found[0] });
          } catch {
            // malformed gh output for this one commit — skip it, don't abort the report
          }
        }
      }
      if (commitsWithoutPr.length > GH_PR_LOOKUP_BOUND) {
        ghPrLookupWarning =
          `${commitsWithoutPr.length - GH_PR_LOOKUP_BOUND} commit(s) without a squash-merge PR number were NOT ` +
          `looked up via gh (bounded to ${GH_PR_LOOKUP_BOUND} to keep report generation fast) — see the commit list for the full set.`;
      }
    } else {
      ghPrLookupWarning = `${commitsWithoutPr.length} commit(s) have no "(#N)" in their subject and gh/git-remote could not resolve owner/repo, so their PR could not be looked up.`;
    }
  }
  if (ghPrLookupWarning) warn(ghPrLookupWarning);

  // CI evidence for the candidate SHA itself.
  const { repo } = resolveGhRepo(repoRoot);
  let ciEvidence = { available: false };
  if (repo) {
    const runsResult = getCheckRuns(repoRoot, candidateSha, repo);
    if (runsResult.ok) {
      ciEvidence = { available: true, ...evaluateRequiredChecks(runsResult.runs) };
    } else {
      warn(`Could not fetch CI check-runs for ${candidateSha} via gh api: ${runsResult.error}`);
    }
  }

  // Release-queue items this candidate would ship: explicitly queued items,
  // plus verified items whose recorded fix commit is in this range.
  const queue = loadReleaseQueue(repoRoot);
  const commitShas = new Set(commits.flatMap((c) => [c.hash, c.short]));
  const includedQueueItems = queue.items.filter((item) =>
    item.status === 'queued_for_release' ||
    (item.status === 'verified' && item.sha && commitShas.has(item.sha)),
  );

  const generatedAt = new Date().toISOString();
  const outPath = args.out ? join(repoRoot, args.out) : join(repoRoot, `docs/releases/${candidateSha}.md`);

  const meta = {
    candidateSha,
    prodSha: prodState.sha,
    prodSource: prodState.source,
    generatedAt,
    commits: commits.map((c) => ({ hash: c.hash, short: c.short, subject: c.subject, prNumber: c.prNumber })),
    prs: [
      ...prsFromSubject.map((n) => ({ number: n, source: 'subject' })),
      ...prsFromGh.map((p) => ({ number: p.number, title: p.title, url: p.url, source: 'gh-search' })),
    ],
    featuresAffected: features.map((f) => ({ id: f.id, name: f.name, criticality: f.criticality, matchedFileCount: f.matchedFiles.length })),
    overallRisk,
    r3Files: r3Files.map((f) => f.file),
    migrations,
    queueItemsIncluded: includedQueueItems.map((i) => i.id),
    ciRequiredChecks: ciEvidence,
  };

  const md = renderReport({ meta, features, commits, includedQueueItems, rangeWarning, ghPrLookupWarning, prodState });

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, md, 'utf-8');

  const summary = {
    path: outPath.startsWith(repoRoot) ? outPath.slice(repoRoot.length).replace(/^\/+/, '') : outPath,
    candidateSha,
    prodSha: prodState.sha,
    overallRisk,
    commitCount: commits.length,
    featureCount: features.length,
    r3FileCount: r3Files.length,
    queueItemsIncluded: meta.queueItemsIncluded,
  };

  if (args.json) {
    process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`);
  } else {
    process.stdout.write(`\nWrote ${summary.path}\n`);
    process.stdout.write(`  candidate: ${candidateSha}\n  production: ${prodState.sha ?? '(unresolved)'}\n`);
    process.stdout.write(`  overall risk: ${overallRisk}${overallRisk === 'R3' ? '  *** R3 — approval-gated ***' : ''}\n`);
    process.stdout.write(`  commits: ${commits.length}  features: ${features.length}  queue items included: ${meta.queueItemsIncluded.length}\n\n`);
  }
}

function renderReport({ meta, features, commits, includedQueueItems, rangeWarning, ghPrLookupWarning, prodState }) {
  const lines = [];
  lines.push(`<!-- RELEASE_META\n${JSON.stringify(meta, null, 2)}\nEND_RELEASE_META -->`);
  lines.push('');
  lines.push(`# Release candidate ${meta.candidateSha}`);
  lines.push('');
  lines.push('Generated `' + meta.generatedAt + '` by `scripts/release/build-release-candidate.mjs`. Do not hand-edit — regenerate.');
  lines.push('');

  lines.push('## Identity');
  lines.push('');
  lines.push(`- Candidate SHA: \`${meta.candidateSha}\``);
  lines.push(`- Current production SHA: ${prodState.sha ? `\`${prodState.sha}\`` : '**UNRESOLVED**'} (source: ${prodState.source})`);
  if (rangeWarning) lines.push(`- ⚠ ${rangeWarning}`);
  lines.push('');

  lines.push(`## Risk — overall ${meta.overallRisk}${meta.overallRisk === 'R3' ? ' — ⚠ APPROVAL-GATED (privileged/high-blast-radius change present)' : ''}`);
  lines.push('');
  if (meta.r3Files.length) {
    lines.push('R3 files (spec §28 — migration, RLS, auth, secrets, billing, destructive data):');
    lines.push('');
    for (const f of meta.r3Files) lines.push(`- \`${f}\``);
  } else {
    lines.push('No R3 files in this candidate. This is a heuristic, path-based classification — read it as "surfaced for review," not "certified safe."');
  }
  lines.push('');

  lines.push('## Commits');
  lines.push('');
  if (commits.length === 0) {
    lines.push(rangeWarning ? '_Unavailable — see Identity section._' : '_No commits between production and this candidate — production is already current._');
  } else {
    for (const c of commits) {
      // The PR number is only appended when the subject doesn't already end
      // with "(#N)" — the common squash-merge case already carries it, and
      // repeating it read as a copy-paste bug the first time this ran.
      const prSuffix = c.prNumber && !new RegExp(`\\(#${c.prNumber}\\)\\s*$`).test(c.subject) ? ` (#${c.prNumber})` : '';
      lines.push(`- \`${c.short}\` ${c.subject}${prSuffix} — ${c.author}, ${c.date}`);
    }
  }
  lines.push('');

  lines.push('## Pull requests');
  lines.push('');
  if (meta.prs.length === 0) {
    lines.push('_None identified._');
  } else {
    for (const pr of meta.prs) lines.push(`- #${pr.number}${pr.title ? ` — ${pr.title}` : ''}${pr.url ? ` (${pr.url})` : ''}`);
  }
  if (ghPrLookupWarning) lines.push(`\n⚠ ${ghPrLookupWarning}`);
  lines.push('');

  lines.push('## Features affected');
  lines.push('');
  if (features.length === 0) {
    lines.push('_None mapped — either no product files changed, or changed files are not covered by memory/registry.yml (a real gap; see AGENTS.md "Feature awareness")._');
  } else {
    for (const f of features) {
      const shown = f.matchedFiles.slice(0, 8).map((x) => `\`${x}\``).join(', ');
      const more = f.matchedFiles.length > 8 ? `, +${f.matchedFiles.length - 8} more` : '';
      lines.push(`- **${f.name}** (\`${f.id}\`, criticality: ${f.criticality}) — ${f.matchedFiles.length} file(s): ${shown}${more}`);
    }
  }
  lines.push('');

  lines.push('## Migrations');
  lines.push('');
  lines.push(meta.migrations.length ? meta.migrations.map((m) => `- \`${m}\``).join('\n') : '_None._');
  lines.push('');

  lines.push('## Incidents fixed / unresolved incidents');
  lines.push('');
  lines.push('_Not yet tracked — `memory/incidents/` is scoped to a later phase (spec §29 observer/healer/verifier, P4). This section will populate once that lands; treat its absence here as "not measured," not "none."_');
  lines.push('');

  lines.push('## Release-queue items included');
  lines.push('');
  if (includedQueueItems.length === 0) {
    lines.push('_None — either the queue is empty or nothing in it matched this commit range._');
  } else {
    for (const i of includedQueueItems) {
      lines.push(`- \`${i.id}\` (${i.feature_id ?? 'unknown feature'}, status: ${i.status}, risk: ${i.risk ?? 'unstated'})`);
    }
  }
  lines.push('');

  lines.push('## Test evidence / CI evidence');
  lines.push('');
  if (!meta.ciRequiredChecks.available) {
    lines.push(`_Could not fetch check-runs for this SHA via \`gh api\` — run \`npm run release:check -- --sha ${meta.candidateSha}\` locally with \`gh\` authenticated before relying on this report._`);
  } else {
    const c = meta.ciRequiredChecks;
    lines.push(c.allRequiredGreen
      ? 'All 6 required checks (`.github/branch-protection.md`) are green on this SHA.'
      : '⚠ Not all required checks are green on this SHA:');
    if (c.missing?.length) lines.push(`- Missing (never posted): ${c.missing.join(', ')}`);
    if (c.notGreen?.length) lines.push(`- Not green: ${c.notGreen.map((n) => `${n.name} (${n.conclusion ?? n.status})`).join(', ')}`);
    if (c.otherRed?.length) lines.push(`- Other non-required, non-advisory checks currently red: ${c.otherRed.map((n) => n.name).join(', ')}`);
  }
  lines.push('');

  lines.push('## Known risks');
  lines.push('');
  lines.push(meta.overallRisk === 'R3'
    ? '⚠ This candidate includes R3 (privileged/high-blast-radius) changes — owner review of the specific migration/RLS/auth diff is required beyond this automated report (spec §28).'
    : 'No R3 changes. Review the R2 feature-behavior items above for product-facing risk before approving.');
  lines.push('');

  lines.push('## Rollback considerations');
  lines.push('');
  const prevDesc = prodState.sha
    ? `\`${prodState.sha}\`${prodState.deploymentId ? ` (deployment \`${prodState.deploymentId}\`)` : ''}`
    : 'unknown';
  lines.push(`- Previous production SHA: ${prevDesc}. Roll back by re-running the production-release workflow with that SHA as \`candidate_sha\`, or \`vercel rollback\` to that deployment id.`);
  lines.push(meta.migrations.length
    ? `- ⚠ This candidate includes ${meta.migrations.length} migration(s) — confirm each has a safe down path or is additive-only before assuming rollback is clean. A schema rollback is NOT automatic.`
    : '- No migrations in this candidate — rollback is a plain redeploy of the previous SHA.');
  lines.push('');

  lines.push('## Post-deploy checks');
  lines.push('');
  lines.push('- `.github/workflows/production-release.yml`\'s verification job: `/` and `/golf/login` return 200, deployment alias confirmed moved, release SHA best-effort confirmed in the served JS bundle.');
  lines.push('- Manual, per spec §27: Sentry release activity, Bridge feature health for the features listed above, confirm any targeted incidents stopped recurring. A green smoke check is not production evidence for those by itself — do not mark a release-queue item `verified_in_production` from a green deploy alone.');
  lines.push('');

  return lines.join('\n');
}

main().catch((err) => {
  process.stderr.write(`release:prepare crashed: ${err?.stack ?? err}\n`);
  process.exit(2);
});
